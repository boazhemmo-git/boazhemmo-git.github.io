#!/usr/bin/env python3
"""Run go2rtc and mi-cam-watch automatically when Windows starts.

Run from a Command Prompt opened with "Run as administrator":

    python autostart.py install --go2rtc C:\\go2rtc\\go2rtc_win64\\go2rtc.exe
    python autostart.py start      # start now instead of waiting for a reboot
    python autostart.py status
    python autostart.py stop       # stop both (until the next start or reboot)
    python autostart.py remove     # stop and uninstall

`install` registers a Task Scheduler task that runs at boot, before anyone logs
in, as the SYSTEM account. It restarts go2rtc or the detector if either exits,
and writes their output to logs\\go2rtc.log and logs\\watch.log.
"""
from __future__ import annotations

import argparse
import subprocess
import sys
from pathlib import Path
from xml.sax.saxutils import escape

TASK = "mi-cam-watch"
HERE = Path(__file__).resolve().parent
RUN_ALL = HERE / "run-all.bat"
RUN_GO2RTC = HERE / "run-go2rtc.bat"
TASK_XML = HERE / "autostart-task.xml"

# `timeout` needs a console, which a boot task does not have; ping waits instead.
SLEEP_10S = "ping -n 11 127.0.0.1 >nul"


def run_all_bat(python: str) -> str:
    return f"""@echo off
rem Generated by autostart.py - edit that, not this file.
rem Starts go2rtc and the detector, restarting either one if it exits.
set OPENCV_FFMPEG_LOGLEVEL=-8
cd /d "{HERE}"
if not exist logs mkdir logs
if exist logs\\watch.log move /y logs\\watch.log logs\\watch.previous.log >nul
if exist logs\\go2rtc.log move /y logs\\go2rtc.log logs\\go2rtc.previous.log >nul
start "go2rtc" /b "{RUN_GO2RTC}"
:loop
"{python}" -u watch.py >> logs\\watch.log 2>&1
echo %date% %time% watch.py exited, restarting in 10 s >> logs\\watch.log
{SLEEP_10S}
goto loop
"""


def run_go2rtc_bat(go2rtc: Path) -> str:
    return f"""@echo off
rem Generated by autostart.py - edit that, not this file.
cd /d "{go2rtc.parent}"
:loop
"{go2rtc}" >> "{HERE}\\logs\\go2rtc.log" 2>&1
echo %date% %time% go2rtc exited, restarting in 10 s >> "{HERE}\\logs\\go2rtc.log"
{SLEEP_10S}
goto loop
"""


def task_xml() -> str:
    # Written as XML rather than with `schtasks /create` flags, because the
    # defaults those flags leave behind would stop the task after 3 days and
    # whenever the laptop runs on battery.
    return f"""<?xml version="1.0" encoding="UTF-16"?>
<Task version="1.2" xmlns="http://schemas.microsoft.com/windows/2004/02/mit/task">
  <RegistrationInfo>
    <Description>mi-cam-watch: go2rtc camera bridge and person/animal detector</Description>
  </RegistrationInfo>
  <Triggers>
    <BootTrigger>
      <Enabled>true</Enabled>
      <Delay>PT30S</Delay>
    </BootTrigger>
  </Triggers>
  <Principals>
    <Principal id="Author">
      <UserId>S-1-5-18</UserId>
      <RunLevel>HighestAvailable</RunLevel>
    </Principal>
  </Principals>
  <Settings>
    <MultipleInstancesPolicy>IgnoreNew</MultipleInstancesPolicy>
    <DisallowStartIfOnBatteries>false</DisallowStartIfOnBatteries>
    <StopIfGoingOnBatteries>false</StopIfGoingOnBatteries>
    <AllowHardTerminate>true</AllowHardTerminate>
    <StartWhenAvailable>true</StartWhenAvailable>
    <RunOnlyIfNetworkAvailable>false</RunOnlyIfNetworkAvailable>
    <IdleSettings>
      <StopOnIdleEnd>false</StopOnIdleEnd>
      <RestartOnIdle>false</RestartOnIdle>
    </IdleSettings>
    <AllowStartOnDemand>true</AllowStartOnDemand>
    <Enabled>true</Enabled>
    <Hidden>false</Hidden>
    <RunOnlyIfIdle>false</RunOnlyIfIdle>
    <WakeToRun>false</WakeToRun>
    <ExecutionTimeLimit>PT0S</ExecutionTimeLimit>
    <Priority>7</Priority>
  </Settings>
  <Actions Context="Author">
    <Exec>
      <Command>{escape(str(RUN_ALL))}</Command>
      <WorkingDirectory>{escape(str(HERE))}</WorkingDirectory>
    </Exec>
  </Actions>
</Task>
"""


def sh(*args: str, check: bool = True) -> subprocess.CompletedProcess:
    r = subprocess.run(list(args), text=True, capture_output=True)
    if check and r.returncode:
        msg = (r.stderr or r.stdout).strip()
        hint = ("\nIs it installed? Run: python autostart.py install --go2rtc <path>"
                if "cannot find" in msg.lower() else "")
        raise SystemExit(f"{args[0]} failed: {msg}{hint}")
    return r


def require_admin() -> None:
    import ctypes
    if not ctypes.windll.shell32.IsUserAnAdmin():
        raise SystemExit("Run this from a Command Prompt opened with 'Run as administrator'.")


def kill_processes() -> None:
    """Stop the restart loops first, then the programs they started."""
    ps = (
        "Get-CimInstance Win32_Process | Where-Object { "
        "($_.Name -eq 'cmd.exe' -and ($_.CommandLine -like '*run-all.bat*' -or "
        "$_.CommandLine -like '*run-go2rtc.bat*')) } | "
        "ForEach-Object { Stop-Process -Id $_.ProcessId -Force -ErrorAction SilentlyContinue }; "
        "Get-CimInstance Win32_Process | Where-Object { "
        "($_.Name -like 'python*.exe' -and $_.CommandLine -like '*watch.py*') -or "
        "$_.Name -eq 'go2rtc.exe' } | "
        "ForEach-Object { Stop-Process -Id $_.ProcessId -Force -ErrorAction SilentlyContinue }"
    )
    sh("powershell", "-NoProfile", "-Command", ps, check=False)


def write_files(go2rtc: Path) -> None:
    RUN_ALL.write_text(run_all_bat(sys.executable).replace("\n", "\r\n"), encoding="utf-8")
    RUN_GO2RTC.write_text(run_go2rtc_bat(go2rtc).replace("\n", "\r\n"), encoding="utf-8")
    TASK_XML.write_text(task_xml(), encoding="utf-16")


def main() -> None:
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    sub = ap.add_subparsers(dest="cmd", required=True)
    inst = sub.add_parser("install")
    inst.add_argument("--go2rtc", required=True, help="full path to go2rtc.exe")
    inst.add_argument("--dry-run", action="store_true", help="only write the files")
    for name in ("start", "stop", "status", "remove"):
        sub.add_parser(name)
    args = ap.parse_args()

    if args.cmd == "install":
        go2rtc = Path(args.go2rtc)
        if not go2rtc.is_file() and not args.dry_run:
            raise SystemExit(f"{go2rtc} not found")
        if not (HERE / "config.toml").is_file() and not args.dry_run:
            raise SystemExit(f"config.toml not found in {HERE}. Run autostart.py from the "
                             "mi-cam-watch folder (cd C:\\camwatch\\mi-cam-watch).")
        write_files(go2rtc)
        if args.dry_run:
            print(f"wrote {RUN_ALL.name}, {RUN_GO2RTC.name}, {TASK_XML.name}")
            return
        require_admin()
        sh("schtasks", "/create", "/tn", TASK, "/xml", str(TASK_XML), "/f")
        print(f"Installed. go2rtc and the detector now start at every boot.\n"
              f"Start them now with:  python autostart.py start\n"
              f"Logs:                 {HERE / 'logs'}")
    elif args.cmd == "start":
        require_admin()
        sh("schtasks", "/run", "/tn", TASK)
        print(f"Started. Dashboard: http://127.0.0.1:8765/  Logs: {HERE / 'logs'}")
    elif args.cmd == "stop":
        require_admin()
        sh("schtasks", "/end", "/tn", TASK, check=False)
        kill_processes()
        print("Stopped. It starts again at the next boot, or with: python autostart.py start")
    elif args.cmd == "status":
        r = sh("schtasks", "/query", "/tn", TASK, "/fo", "list", check=False)
        print(r.stdout.strip() or "Not installed.")
    elif args.cmd == "remove":
        require_admin()
        sh("schtasks", "/end", "/tn", TASK, check=False)
        kill_processes()
        sh("schtasks", "/delete", "/tn", TASK, "/f", check=False)
        for f in (RUN_ALL, RUN_GO2RTC, TASK_XML):
            f.unlink(missing_ok=True)
        print("Removed.")


if __name__ == "__main__":
    main()
